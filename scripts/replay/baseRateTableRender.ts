/**
 * Renders `src/domain/analysis/measuredBaseRates.ts` (WP-18 §4.1) from the computed table.
 * Pure: rows in, source text out; `baseRateTable.ts` formats it with the repository's
 * prettier config so the committed file is stable. The file holds aggregate statistics only
 * (no bars, no prices) and a header that says which runs it was measured on.
 */
import {
    BASE_RATE_MIN_N,
    type BaseRateRow,
    type SubjectTable,
} from './baseRateTableCompute';

export interface TableHeader {
    setId: string;
    fingerprint: string;
    coreSha: string;
    definitions: string;
    date: string;
    command: string;
}

const round6 = (value: number): number => Number(value.toFixed(6));

const literal = (value: string): string => `'${value.replaceAll("'", "\\'")}'`;

function rowSource(row: BaseRateRow): string {
    const { difference, scope } = row;
    return `{
    subject: ${literal(row.subject)},
    key: ${literal(row.key)},
    n: ${row.n},
    eventShare: ${round6(row.eventShare)},
    placeboShare: ${round6(row.placeboShare)},
    difference: {
        mean: ${round6(difference.mean)},
        low: ${round6(difference.low)},
        high: ${round6(difference.high)},
    },
    verdict: ${literal(row.verdict)},
    scope: {
        timeframe: ${literal(scope.timeframe)},
        symbols: ${scope.symbols},
        from: ${literal(scope.from)},
        to: ${literal(scope.to)},
    },
}`;
}

const recordSource = (table: SubjectTable): string =>
    table.rows
        .map(({ family, row }) => `${literal(family)}: ${rowSource(row)},`)
        .join('\n');

export function renderBaseRateTable(input: {
    header: TableHeader;
    patterns: SubjectTable;
    candles: SubjectTable;
    priceLevel: BaseRateRow;
    priceLevelFamilies: SubjectTable;
}): string {
    const { header } = input;
    return `/**
 * GENERATED by scripts/replay/baseRateTable.ts. Do not edit by hand: change the instrument
 * and regenerate.
 *
 * Measured base rates of the engines' claims on the replay set (daily bars, aggregate
 * statistics only). Each row compares an event's outcome with a matched placebo (the same
 * outcome on other dates of the same symbol) and says whether it beats it.
 *
 * Set: ${header.setId}, bars fingerprint ${header.fingerprint}
 * Core: ${header.coreSha} (${header.coreSha.endsWith('+dirty') ? 'DIRTY checkout: do not commit' : 'clean checkout'})
 * Definitions: ${header.definitions}
 * Generated: ${header.date}
 * Command: ${header.command}
 */
import type { ChartPatternId, Timeframe } from '@/domain/types';

/** The sample floor of a family row and of the verdict rule (CP-11). */
export const BASE_RATE_MIN_N = ${BASE_RATE_MIN_N};

/** What a base-rate row measures. Tier 4, both entrypoints (API-3). */
export type BaseRateSubject = 'chart_pattern' | 'candle_pattern' | 'price_level';

/** Whether a row beats its placebo (the WP-17 G3 rule), has no edge, or has too few events. */
export type BaseRateVerdict = 'beats_placebo' | 'no_edge' | 'insufficient_sample';

export interface MeasuredBaseRate {
    readonly subject: BaseRateSubject;
    /** ChartPatternId, candle pattern name, or 'pooled' when the family has n < BASE_RATE_MIN_N. */
    readonly key: string;
    readonly n: number;
    /**
     * chart_pattern: target before invalidation within 60 bars; candle_pattern: next-5-bar
     * move in the label's direction; price_level: held after a touch (closed 0.5 ATR back on
     * the level's side before closing 0.5 ATR through it, within 10 bars).
     */
    readonly eventShare: number;
    /** The same outcome for the matched placebo (date transplant; candles matched on the prior-move bucket). */
    readonly placeboShare: number;
    /** eventShare - placeboShare, with its 95% week-cluster bootstrap interval. */
    readonly difference: {
        readonly mean: number;
        readonly low: number;
        readonly high: number;
    };
    readonly verdict: BaseRateVerdict;
    readonly scope: {
        readonly timeframe: '1Day';
        readonly symbols: number;
        readonly from: string;
        readonly to: string;
    };
}

/**
 * The pooled measurement of all chart patterns across the whole replay set: its own sample, placebo
 * comparison and verdict. Read this for a statement about chart patterns as a whole.
 *
 * The per-family 'pooled' rows inside PATTERN_BASE_RATES are copies of this row's numbers for a
 * family below BASE_RATE_MIN_N events: they carry verdict 'insufficient_sample' (that
 * family's own sample is too small), which is not this measurement's verdict.
 */
export const PATTERN_POOLED_BASE_RATE: MeasuredBaseRate = ${rowSource(input.patterns.pooled.row)};

/**
 * The pooled measurement of all directional candles across the whole replay set: its own sample, placebo
 * comparison and verdict. Read this for a statement about directional candles as a whole.
 *
 * The per-family 'pooled' rows inside CANDLE_BASE_RATES are copies of this row's numbers for a
 * family below BASE_RATE_MIN_N events: they carry verdict 'insufficient_sample' (that
 * family's own sample is too small), which is not this measurement's verdict.
 */
export const CANDLE_POOLED_BASE_RATE: MeasuredBaseRate = ${rowSource(input.candles.pooled.row)};

export const PATTERN_BASE_RATES: Readonly<
    Partial<Record<ChartPatternId, MeasuredBaseRate>>
> = {
${recordSource(input.patterns)}
};

export const CANDLE_BASE_RATES: Readonly<Record<string, MeasuredBaseRate>> = {
${recordSource(input.candles)}
};

export const PRICE_LEVEL_BASE_RATE: MeasuredBaseRate = ${rowSource(input.priceLevel)};

/**
 * The same measurement per kind family of the printed price levels (fib, vp, swing, ma,
 * round, pivot, ichimoku, band, supertrend, vwap, avwap), pooled across the symbols of the set
 * (see \`scope\`), both markets and every period: a claim made from a row must say so and
 * give its \`n\` (resolved touches). Read it through \`priceLevelFamilyBaseRateFor\`: a family
 * with fewer than BASE_RATE_MIN_N touches, or none, carries the pooled figures of
 * \`PRICE_LEVEL_BASE_RATE\` under \`key: 'pooled'\` with \`insufficient_sample\`, and such a
 * row is NOT the family's measurement. A family's p is reconstructed from its stored interval
 * (normal approximation), not the bootstrap p, and its split by market and half is not
 * measured, so no family can read \`beats_placebo\`. Never a statement about a single level of
 * a report.
 */
export const PRICE_LEVEL_FAMILY_BASE_RATES: Readonly<
    Record<string, MeasuredBaseRate>
> = {
${recordSource(input.priceLevelFamilies)}
};

/**
 * The measured base rate of a price-level kind family, or \`null\` when the family has no
 * measurement of its own: it is not in the table, or its row is the pooled figures under
 * \`insufficient_sample\` (too few touches, or none).
 */
export function priceLevelFamilyBaseRateFor(
    family: string
): MeasuredBaseRate | null {
    const row = Object.entries(PRICE_LEVEL_FAMILY_BASE_RATES).find(
        ([key]) => key === family
    )?.[1];
    return row === undefined ||
        row.key !== family ||
        row.verdict === 'insufficient_sample'
        ? null
        : row;
}

/**
 * The measured base rate of a detected pattern or candle; \`null\` off daily bars (nothing
 * was measured there). A key without an own row of enough events gets the pooled row.
 */
export function measuredBaseRateFor(
    subject: 'chart_pattern' | 'candle_pattern',
    key: string,
    timeframe: Timeframe
): MeasuredBaseRate | null {
    if (timeframe !== '1Day') return null;
    if (subject === 'chart_pattern') {
        return (
            Object.entries(PATTERN_BASE_RATES).find(([id]) => id === key)?.[1] ??
            PATTERN_POOLED_BASE_RATE
        );
    }
    return (
        Object.entries(CANDLE_BASE_RATES).find(([name]) => name === key)?.[1] ??
        CANDLE_POOLED_BASE_RATE
    );
}
`;
}
